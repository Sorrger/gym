// Obwody: card in Postępy → Ciało, add / validate / edit / move day / delete, saved to IndexedDB, in the file export, English
import { launch } from './lib.mjs'
import { devices } from 'playwright-core'
import { seed, load } from './seed.mjs'
const b = await launch()
const ctx = await b.newContext({ ...devices['iPhone 15'] }); await ctx.addInitScript(() => { localStorage.setItem('onboarded', '1') })
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message))
let fails = 0
const ok = (c, m, x) => { if (!c) { fails++; console.log('FAIL', m, x ?? '') } else console.log('ok  ', m) }
const idb = key => p.evaluate(k => new Promise(res => { const r = indexedDB.open('keyval-store'); r.onsuccess = () => { const q = r.result.transaction('keyval').objectStore('keyval').get(k); q.onsuccess = () => res(q.result) } }), key)
await load(p, seed())
await p.goto('http://localhost:4173/#/tabs/progress'); await p.reload(); await p.waitForTimeout(1300)
await p.locator('.ptabs button:visible', { hasText: 'Ciało' }).click(); await p.waitForTimeout(400)
ok((await p.locator('.mcard:visible').innerText()).includes('Dodaj obwody'), 'empty card on Ciało')
await p.locator('.mcard:visible').click(); await p.waitForTimeout(1200)
ok(p.url().endsWith('#/measures'), 'card opens the page', p.url())
await p.locator('.btns button:has-text("Dodaj obwody")').click(); await p.waitForTimeout(300)
await p.locator('.btn:has-text("Zapisz")').click(); await p.waitForTimeout(200)
ok((await p.locator('.ed-err').innerText()).includes('przynajmniej'), 'empty form refused')
const inp = name => p.locator('.ed-row', { has: p.locator('.ed-name b', { hasText: new RegExp('^' + name + '$') }) }).locator('input')
await inp('Talia').fill('5'); await p.locator('.btn:has-text("Zapisz")').click(); await p.waitForTimeout(200)
ok((await p.locator('.ed-err').innerText()).includes('Talia'), 'out-of-range value refused')
await p.locator('.ed-date').fill('2026-10-01')
await inp('Talia').fill('95'); await inp('Ramię').fill('40,5')
await p.locator('.btn:has-text("Zapisz")').click(); await p.waitForTimeout(400)
await p.locator('.btns button:has-text("Dodaj obwody")').click(); await p.waitForTimeout(300)
await inp('Talia').fill('92,5'); await inp('Ramię').fill('41')
await p.locator('.btn:has-text("Zapisz")').click(); await p.waitForTimeout(600)
const parts = (await p.locator('.parts').innerText()).replace(/\s+/g, ' ')
ok(/Talia.*92,5 cm.*−2,5/.test(parts) && /Ramię.*41 cm.*\+0,5/.test(parts), 'per part: last value and change', parts)
ok(await p.locator('.parts .ok').count() === 2, 'both changes green (waist down, arm up)')
ok(await p.locator('.spark').count() === 2, 'sparklines')
const st = await idb('measures')
ok(st && st['2026-10-01']?.v.waist === 95 && Object.keys(st).length === 2, 'saved in IndexedDB', st)
// edit the old day: move it to another date
await p.locator('.row', { hasText: '01.10' }).click(); await p.waitForTimeout(300)
ok((await p.locator('.editor').innerText()).includes('Popraw'), 'editor for an existing day')
await p.locator('.ed-date').fill('2026-10-02'); await p.locator('.btn:has-text("Zapisz")').click(); await p.waitForTimeout(400)
const st2 = await idb('measures')
ok(st2['2026-10-01'].del && st2['2026-10-02']?.v.waist === 95, 'moved day: old one tombstoned', st2)
await p.locator('.row', { hasText: '02.10' }).click(); await p.waitForTimeout(300)
await p.locator('.btn:has-text("Usuń pomiar")').click(); await p.waitForTimeout(300)
await p.locator('.dlg-btn:has-text("Usuń")').click(); await p.waitForTimeout(400)
ok(await p.locator('.part').count() === 2 && !(await p.locator('.parts').innerText()).includes('−'), 'deleted day gone from the numbers')
await p.screenshot({ path: 'measures.png' })
// back to Ciało: card shows the waist
await p.goto('http://localhost:4173/#/tabs/progress'); await p.reload(); await p.waitForTimeout(1300)
await p.locator('.ptabs button:visible', { hasText: 'Ciało' }).click(); await p.waitForTimeout(400)
ok((await p.locator('.mcard:visible').innerText()).replace(/\s+/g, ' ').includes('Talia 92,5 cm'), 'card shows the waist first')
// English
await p.evaluate(() => localStorage.setItem('lang', 'en'))
await p.goto('http://localhost:4173/#/measures'); await p.reload(); await p.waitForTimeout(1500)
const en = (await p.locator('ion-content:visible').innerText()).replace(/\s+/g, ' ')
ok(en.includes('Measurements') && en.includes('Waist 92.5') && en.includes('Last measured') && !/Talia|Ramię|Dodaj/.test(en), 'English page', en.slice(0, 300))
await p.locator('.btns button').click(); await p.waitForTimeout(300)
const ed = (await p.locator('.editor').innerText()).replace(/\s+/g, ' ')
ok(!/Najw|Pod pachami|Talia/.test(ed), 'English editor', ed.slice(0, 200))
ok(!errs.length, 'no page errors', errs)
await b.close()
if (fails) { console.log(fails + ' FAILED'); process.exit(1) }
