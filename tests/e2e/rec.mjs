import { chromium, devices } from 'playwright-core'
import { seed, load } from './seed.mjs'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' })
const ctx = await b.newContext({ ...devices['iPhone 15'] }); await ctx.addInitScript(() => localStorage.setItem('onboarded', '1'))
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message))
await load(p, seed())
await p.goto('http://localhost:4173/#/plan/0'); await p.reload(); await p.waitForTimeout(1500); await p.locator('.go:visible').click(); await p.waitForTimeout(1800)
await p.locator('.dlg-btn:visible').last().click().catch(() => {}); await p.waitForTimeout(300)
for (let i = 0; i < 4; i++) await p.locator('button[aria-label^="Plus 2"]:visible').first().click()
await p.locator('button.check:visible').first().click(); await p.waitForTimeout(600)
console.log('record pop:', await p.locator('.rec-pop').count(), (await p.locator('.rec-pop').innerText().catch(() => '')).replace(/\s+/g, ' '))
await p.screenshot({ path: 'rec-pop.png' })
await p.locator('.tb-finish:visible').click(); await p.waitForTimeout(1200)
console.log('summary rec card:', (await p.locator('.rec-card').innerText().catch(() => 'none')).replace(/\s+/g, ' '))
await p.screenshot({ path: 'rec-sum.png' })
await p.locator('.save-btn').click(); await p.waitForTimeout(1200)
// settings menu + a section
await p.goto('http://localhost:4173/#/settings'); await p.reload(); await p.waitForTimeout(1400)
console.log('menu:', (await p.locator('.menu .row b').allInnerTexts()).join(' | '))
await p.screenshot({ path: 'set-menu.png' })
await p.locator('.menu .row', { hasText: 'Progresja' }).click(); await p.waitForTimeout(1200)
console.log('progress page:', p.url().split('#')[1], await p.locator('h1.t-large:visible').innerText(), 'rows', await p.locator('.row.every:visible').count())
await p.locator('.back:visible').click(); await p.waitForTimeout(1000); console.log('back →', p.url().split('#')[1])
await p.locator('.menu .row', { hasText: 'Kopia' }).click(); await p.waitForTimeout(1200); console.log('backup page has export:', await p.locator('.row:visible', { hasText: 'Zapisz kopię do pliku' }).count())
// colour in editor
await p.goto('http://localhost:4173/#/plan/1/edit'); await p.reload(); await p.waitForTimeout(1400)
await p.locator('.col').nth(8).click(); await p.locator('.save:visible').click(); await p.waitForTimeout(2500)
await p.goto('http://localhost:4173/#/tabs/train'); await p.reload(); await p.waitForTimeout(1500)
console.log('saved colour:', await p.evaluate(() => new Promise(res => { const r = indexedDB.open('keyval-store'); r.onsuccess = () => { const q = r.result.transaction('keyval').objectStore('keyval').get('plan'); q.onsuccess = () => res(JSON.stringify(q.result?.days?.[1]?.color)) } }))); await p.screenshot({ path: 'col.png' })
console.log('errs', errs); await b.close()
