// Exercise catalogue in the plan editor: search, options change name + muscles, pick fills the row, save,
// the new exercise works in a workout; a basic-plan combination returns the plan's own name; English names.
import { launch } from './lib.mjs'
import { devices } from 'playwright-core'
const b = await launch()
const ctx = await b.newContext({ ...devices['iPhone 15'] }); await ctx.clock.install({ time: new Date('2026-11-24T12:00:00') })
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message + ' @ ' + p.url()))
const res = []; const ok = (c, m) => res.push((c ? 'ok   ' : 'FAIL ') + m)
const go = async h => { await p.goto('http://localhost:4173/' + h); await p.reload(); await p.waitForTimeout(1400) }
const sheet = p.locator('ion-modal.ex-sheet')
await go('#/plan/0/edit')
const n0 = await p.locator('.card.ex').count()
await p.locator('button.add').click(); await p.waitForTimeout(800)
ok(await sheet.locator('.ep-row').count() > 50, 'add exercise opens the catalogue with the list')
await p.screenshot({ path: 'cat-list.png' })
await sheet.locator('.ep-search').fill('francuz'); await p.waitForTimeout(200)
ok((await sheet.locator('.ep-row b').allTextContents()).some(t => /francuskie/.test(t)), 'colloquial name finds the exercise (francuz)')
await sheet.locator('.ep-search').fill('przysiad'); await p.waitForTimeout(200)
ok((await sheet.locator('.ep-row b').allTextContents()).length > 3, 'search filters by name')
await sheet.locator('.ep-search').fill('')
await sheet.locator('.gchip', { hasText: 'Klatka' }).click()
ok((await sheet.locator('h4').allTextContents()).join() === 'Klatka', 'muscle group chip filters the list')
await sheet.locator('.ep-row', { hasText: 'Wyciskanie na ławce' }).click(); await p.waitForTimeout(300)
const nm = () => sheet.locator('.ep-name').textContent()
ok(await nm() === 'Wyciskanie sztangi na ławce płaskiej', 'default options = the plan exercise (same history)')
await sheet.locator('.ochip', { hasText: 'hantle' }).click(); await sheet.locator('.ochip', { hasText: 'wąsko' }).click()
ok(await nm() === 'Wyciskanie na ławce – hantle, wąsko', 'options build the name: ' + await nm())
ok(/Triceps/.test(await sheet.locator('.ep-info p').first().textContent()), 'close grip: triceps becomes a main muscle')
await p.screenshot({ path: 'cat-pl.png' })
await sheet.locator('.ep-pick').click(); await p.waitForTimeout(700)
const last = p.locator('.card.ex').nth(n0)
ok(await last.locator('input.name').inputValue() === 'Wyciskanie na ławce – hantle, wąsko', 'pick fills the name')
ok(/Klatka.*Triceps|Triceps.*Klatka/.test(await last.locator('.mus b').textContent()), 'pick fills the muscles')
ok(await last.locator('.rng input').first().inputValue() === '6', 'pick fills the rep range')
// second: bodyweight dips with the assisted machine on another row via the row button
await last.locator('.cat').first().click(); await p.waitForTimeout(700)
ok(await sheet.locator('.ep-name').textContent() === 'Wyciskanie na ławce – hantle, wąsko' && await sheet.locator('.ochip.on', { hasText: 'wąsko' }).count() === 1, 'reopening starts on the chosen options')
await sheet.locator('.ep-back').click(); await p.waitForTimeout(200)
await sheet.locator('.ep-search').fill('poręczach'); await sheet.locator('.ep-row').first().click(); await p.waitForTimeout(200)
await sheet.locator('.ochip', { hasText: 'masa ciała' }).click()
ok(/Powtórzenia/.test(await sheet.locator('.unit').textContent()), 'bodyweight → reps')
await sheet.locator('.ochip', { hasText: 'wspomaganiem' }).click()
ok(/Ciężar/.test(await sheet.locator('.unit').textContent()) && await sheet.locator('.ep-how', { hasText: 'wspomagania' }).count() === 1, 'assisted machine → kg of help')
await sheet.locator('.ep-back').click(); await p.waitForTimeout(200)
ok(await sheet.locator('.ep-row').count() > 0, 'back to the list')
await sheet.locator('.ep-x').click(); await p.waitForTimeout(600)
// cancel right after "Dodaj ćwiczenie" leaves no empty row
const n1 = await p.locator('.card.ex').count()
await p.locator('button.add').click(); await p.waitForTimeout(700); await sheet.locator('.ep-x').click(); await p.waitForTimeout(600)
ok(await p.locator('.card.ex').count() === n1, 'closing the catalogue after "Dodaj ćwiczenie" adds no empty row')
// duplicate in the same training is flagged at once
await p.locator('button.add').click(); await p.waitForTimeout(700)
await sheet.locator('.ep-row', { hasText: 'Wyciskanie na ławce' }).click(); await p.waitForTimeout(200)
await sheet.locator('.ep-pick').click(); await p.waitForTimeout(700)
ok(/już jest w planie/.test(await p.locator('.dlg h2:visible').textContent().catch(() => '')), 'picking an exercise that is already in the training warns')
while (await p.locator('.dlg-btn:visible').count()) { await p.locator('.dlg-btn:visible').last().click(); await p.waitForTimeout(300) }
await p.locator('.card.ex').last().locator('.del').click(); await p.waitForTimeout(300); await p.locator('.dlg-btn', { hasText: 'Usuń' }).click(); await p.waitForTimeout(400)
// alternative from the catalogue
const lastEx = p.locator('.card.ex').nth(n0)
await lastEx.locator('.cat.small').click(); await p.waitForTimeout(700)
await sheet.locator('.ep-search').fill('chest press'); await sheet.locator('.ep-row', { hasText: 'Wyciskanie przed siebie' }).click(); await p.waitForTimeout(200)
await sheet.locator('.ep-pick').click(); await p.waitForTimeout(600)
ok(/maszyna/.test((await lastEx.locator('.alt-chip').allTextContents()).join()), 'alternative added from the catalogue')
// typing a catalogue name fills its muscles and unit
const n2 = await p.locator('.card.ex').count()
await p.locator('button.add').click(); await p.waitForTimeout(700); await sheet.locator('.ep-x').click(); await p.waitForTimeout(500)
await p.locator('button.add').click(); await p.waitForTimeout(700)
await sheet.locator('.ep-search').fill('plank'); await sheet.locator('.ep-row').first().click(); await sheet.locator('.ep-pick').click(); await p.waitForTimeout(600)
const typed = p.locator('.card.ex').nth(n2)
await typed.locator('input.name').fill('Wypychanie bioder (hip thrust) – hantle'); await typed.locator('input.name').dispatchEvent('change'); await p.waitForTimeout(200)
ok(/Pośladki/.test(await typed.locator('.mus b').textContent()) && await typed.locator('.seg .on').textContent() === 'Ciężar (kg)', 'typing a catalogue name fills muscles and unit')
await p.locator('.save').click(); await p.waitForTimeout(2500)
await go('#/plan/0')
ok(await p.locator('text=Wyciskanie na ławce – hantle, wąsko').count() > 0, 'saved in the plan')
await p.locator('.go:visible').click(); await p.waitForTimeout(1300)
while (await p.locator('.dlg-btn:visible').count()) { await p.locator('.dlg-btn:visible').last().click(); await p.waitForTimeout(350) }
await p.locator('.dots button, .dot').last().click().catch(() => {}); await p.waitForTimeout(600)
ok(errs.length === 0, 'workout opens without errors')
// English
await p.evaluate(() => localStorage.setItem('lang', 'en')); await go('#/plan/0'); await p.waitForTimeout(1200)
ok(await p.locator('text=Bench press – dumbbells, close').count() > 0, 'English name of a catalogue exercise')
await go('#/plan/0/edit'); await p.locator('.card.ex').first().locator('.cat:not(.small)').click(); await p.waitForTimeout(800)
ok(await sheet.locator('.ep-name').textContent() === 'Bench press – barbell', 'English: picker opens on the exercise with its English name')
await sheet.locator('.ep-back').click(); await p.waitForTimeout(300)
ok(await sheet.locator('.ep-row', { hasText: 'Squat' }).count() > 0 && await sheet.locator('h4', { hasText: 'Chest' }).count() === 1, 'catalogue list in English')
await p.screenshot({ path: 'cat-en.png' })
res.forEach(r => console.log(r)); console.log('errs', errs); await b.close()
